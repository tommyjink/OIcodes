#include<bits/stdc++.h>
#define int long long
#define endl "\n"
using namespace std;
const int N=1e6+10,INF=1e18;
int n,a[N],b[N];
void solve()
{
    cin>>n;
    for(int i=1;i<=n;i++)
        cin>>a[i];
    a[0]=-INF,a[n+1]=INF;
    for(int i=1;i<=n;i++)
    {
        if(a[i]>=a[i+1]||a[i]<=a[i-1])
            b[i]=true;
        else b[i]=false;
    }
    int l=1,r=1,ans=0;
    while(l<=n&&r<=n)
    {
        while(l<=n&&!b[l])l++,r=l;
        if(l>n)break;
        while(r<=n&&b[r])r++;
        r--;
        if(a[l]+(r-l-1)<a[r])ans+=((r-l+1)-2+1)/2;
        else ans+=((r-l+1)+1)/2;
        l=r+1;
    }
    cout<<ans<<endl;
}
signed main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    int t;
    cin>>t;
    while(t--)
        solve();
    return 0;
}
